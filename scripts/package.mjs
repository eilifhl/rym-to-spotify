import { mkdtempSync, copyFileSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
const archive = join(mkdtempSync(join(tmpdir(), 'rym-package-')), 'extension.zip');
const files = ['manifest.json', 'README.md', ...readdirSync('dist').map(name => `dist/${name}`)];
const result = spawnSync('zip', ['-q', archive, ...files], { stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
copyFileSync(archive, 'extension.zip');
console.log('Packaged extension.zip');
